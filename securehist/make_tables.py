"""Fill the four new-experiment tables and the sensitivity figure from results_v2/ (no number typed by hand).

Reads   results_v2/hash_baseline/summary.csv      -> Table 1 (hash vs watermark)
        results_v2/eps_sweep/summary.csv          -> Table 2 + Figure (sensitivity)
        results_v2/vlm_band/band_counts.csv       -> Table 3 (band composition)
        results_v2/vlm_band/summary_table.csv     -> Table 4 (auditors on the band)
        results_v2/embed_ablation/summary.csv     -> Table 5 (embedding ablation)
Writes  results_v2/tables/new_tables.md, new_tables.tex, fig_eps_sensitivity.png / .pdf
A table whose source file is missing is skipped with a note, so the script can run after each experiment.

Usage:  python securehist/make_tables.py
"""
import os
import sys

if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass

import numpy as np
import pandas as pd

import common as C

R = os.path.join(C.PROJECT, "results_v2")
OUT = C.out_dir("tables")
CONDS = ["clean", "jpeg90", "fgsm", "pgd20", "pgd20_adapt", "patch64"]


def f1(x, nd=1):
    return "–" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


def pval(p):
    if p is None or (isinstance(p, float) and np.isnan(p)):
        return "–"
    return f"{p:.3f}" if p >= 0.001 else f"{p:.1e}"


def ci(r, k, nd=1):
    if r[k] is None or (isinstance(r[k], float) and np.isnan(r[k])):
        return "– (n = 0)"
    return f"{f1(r[k], nd)} [{f1(r[k + '_lo'], nd)}, {f1(r[k + '_hi'], nd)}]"


def md_table(header, rows):
    s = "| " + " | ".join(header) + " |\n|" + "---|" * len(header) + "\n"
    return s + "".join("| " + " | ".join(map(str, r)) + " |\n" for r in rows) + "\n"


def tex_table(caption, header, rows, label):
    esc = lambda x: str(x).replace("%", r"\%").replace("&", r"\&").replace("≥", r"$\geq$").replace("±", r"$\pm$") \
        .replace("✓", r"\checkmark").replace("✗", r"$\times$").replace("–", "--").replace("σ", r"$\sigma$").replace("∆", r"$\Delta$")
    s = "\\begin{table}[t]\\centering\\small\n\\caption{" + esc(caption) + "}\\label{" + label + "}\n"
    s += "\\begin{tabular}{l" + "c" * (len(header) - 1) + "}\\toprule\n" + " & ".join(map(esc, header)) + " \\\\\\midrule\n"
    s += "".join(" & ".join(map(esc, r)) + " \\\\\n" for r in rows)
    return s + "\\bottomrule\\end{tabular}\\end{table}\n\n"


def read(path):
    p = os.path.join(R, path)
    return pd.read_csv(p) if os.path.exists(p) else None


def main():
    md, tex, missing = ["# New experiment tables\n\nGenerated by `make_tables.py` from `results_v2/`.\n"], [], []

    # ---------------- Table 1
    t = read("hash_baseline/summary.csv")
    if t is not None:
        hdr = ["Method", "In-band", "Localizes", "FPR, PNG re-save", "JPEG-90 flagged", "FGSM", "PGD-20", "Adaptive PGD-20", "Patch 64 px"]
        rows = []
        for _, r in t.iterrows():
            ours = "Watermark" in r["method"]
            rows.append([r["method"], "✓" if ours else "✗", "✓" if ours else "✗"] + [f1(r[c]) for c in CONDS])
        cap = (f"Detection of modified images by a cryptographic hash and by the watermark rule on {int(t['clean_n'].iloc[0]) * 6:,} "
               f"cases ({int(t['clean_n'].iloc[0]):,} test images; %). Source: results_v2/hash_baseline/summary.csv.")
        md += [f"## Table 1\n\n{cap}\n\n", md_table(hdr, rows)]; tex.append(tex_table(cap, hdr, rows, "tab:hash"))
    else:
        missing.append("Table 1 (run eval_hash_band.py)")

    # ---------------- Table 2 + figure
    e = read("eps_sweep/summary.csv")
    if e is not None:
        hdr = ["ε (×1/255)", "Changed", "PSNR (dB)", "WM FGSM", "WM PGD-20", "CNN FGSM", "CNN PGD-20", "Harmful FGSM", "Harmful PGD-20"]
        rows = [[("0 (control)" if r.eps_255 == 0 else f"{r.eps_255:g}"), f1(r.changed), f1(r.psnr_db), f1(r.wm_fgsm), f1(r.wm_pgd20),
                 f1(r.cnn_fgsm), f1(r.cnn_pgd20), f1(r.harmful_fgsm), f1(r.harmful_pgd20)] for r in e.itertuples()]
        n_img = int(e.n_fgsm.iloc[0])
        cap = (f"Detection and diagnostic damage as the attack budget shrinks ({n_img} test images, FGSM and PGD-20; %). "
               "WM = watermark rule flagged; CNN = CNN-confidence flagged (5% false-alarm threshold); Harmful = attack success "
               "against the defended classifier. Source: results_v2/eps_sweep/summary.csv.")
        md += [f"## Table 2\n\n{cap}\n\n", md_table(hdr, rows)]; tex.append(tex_table(cap, hdr, rows, "tab:eps"))
        import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
        xs = np.arange(len(e)); lab = ["0"] + [f"{v:g}" for v in e.eps_255[1:]]
        fig, ax = plt.subplots(1, 2, figsize=(10, 3.8), dpi=200)
        styles = [("wm_pgd20", "Watermark rule, PGD-20", "#2f6db5", "-"), ("wm_fgsm", "Watermark rule, FGSM", "#2f6db5", "--"),
                  ("hash_pgd20", "Pixel hash, PGD-20", "#6b6b6b", "-"), ("cnn_pgd20", "CNN confidence, PGD-20", "#b7791f", "-"),
                  ("cnn_fgsm", "CNN confidence, FGSM", "#b7791f", "--")]
        for col, name, c, ls in styles:
            ax[0].plot(xs, e[col], ls, color=c, marker="o", ms=3.5, label=name)
            ax[0].fill_between(xs, e[col + "_lo"], e[col + "_hi"], color=c, alpha=0.12, lw=0)
        for col, name, ls in (("harmful_pgd20", "PGD-20", "-"), ("harmful_fgsm", "FGSM", "--")):
            ax[1].plot(xs, e[col], ls, color="#c8323f", marker="o", ms=3.5, label=name)
            ax[1].fill_between(xs, e[col + "_lo"], e[col + "_hi"], color="#c8323f", alpha=0.12, lw=0)
        for a, title, yl in ((ax[0], "(a) Attacked cases flagged", "Flagged (%)"), (ax[1], "(b) Harmful attack success, defended CNN", "Harmful ASR (%)")):
            a.set_xticks(xs); a.set_xticklabels(lab); a.set_xlabel("ε (×1/255)"); a.set_ylabel(yl); a.set_ylim(-3, 103)
            a.set_title(title, fontsize=10, loc="left"); a.grid(alpha=0.25); a.spines[["top", "right"]].set_visible(False)
        ax[0].legend(fontsize=7, frameon=False, loc="center right"); ax[1].legend(fontsize=8, frameon=False)
        plt.tight_layout()
        for ext in ("png", "pdf"):
            plt.savefig(os.path.join(OUT, f"fig_eps_sensitivity.{ext}"), bbox_inches="tight")
        plt.close()
        md.append("\n![Sensitivity](fig_eps_sensitivity.png)\n\n")
    else:
        missing.append("Table 2 and figure (run eval_eps_sweep.py)")

    # ---------------- Table 3
    b = read("vlm_band/band_counts.csv")
    if b is not None:
        hdr = ["", "Clean", "JPEG-90", "FGSM", "PGD-20", "Adaptive PGD-20", "Patch 64 px", "Total"]
        rows = [["Cases in band"] + [str(int(b[c].iloc[0])) for c in CONDS + ["total"]]]
        cap = "Composition of the ambiguous band 0.30 ≤ NC < 0.60 by case type (counts). Source: results_v2/vlm_band/band_counts.csv."
        md += [f"## Table 3\n\n{cap}\n\n", md_table(hdr, rows)]; tex.append(tex_table(cap, hdr, rows, "tab:band"))
    else:
        missing.append("Table 3 (run eval_hash_band.py)")

    # ---------------- Table 4
    v = read("vlm_band/summary_table.csv")
    if v is not None:
        hdr = ["Auditor", "Inputs", "n", "Authentic", "FPR", "TPR", "Accuracy", "AUC", "McNemar p vs. rule"]
        rows = [[r.auditor, r.inputs, int(r.n), f1(r.authentic), ci(r._asdict(), "fpr"), ci(r._asdict(), "tpr"),
                 ci(r._asdict(), "accuracy"), f1(r.auc, 2), pval(r.mcnemar_p_vs_rule)] for r in v.itertuples()]
        cap = ("Auditors compared with the threshold rule on the same band cases (%, 95% Wilson intervals). "
               "Authentic = share of AUTHENTIC verdicts. Source: results_v2/vlm_band/summary_table.csv.")
        md += [f"## Table 4\n\n{cap}\n\n", md_table(hdr, rows)]; tex.append(tex_table(cap, hdr, rows, "tab:vlmband"))
    else:
        missing.append("Table 4 (run eval_vlm_band.py)")

    # ---------------- Table 5
    a = read("embed_ablation/summary.csv")
    if a is not None:
        has_ad = "flag_adaptive" in a.columns
        hdr = ["Embedding", "∆", "PSNR", "SSIM", "NC (wm)", "NC (no wm)", "FPR untouched", "JPEG-90 flagged",
               "FGSM / PGD flagged"] + (["Adaptive PGD flagged (NC)"] if has_ad else []) + \
              ["Splice 64 AUC / F1", "Splice 32 detected", "Embed time (s)"]
        rows = [[r.embedding, f1(r.step, 2), f1(r.psnr, 2), f1(r.ssim, 4), f1(r.nc_wm, 3), f1(r.nc_unwm, 3), f1(r.fp_untouched),
                 f1(r.flag_jpeg90), f"{f1(r.flag_fgsm)} / {f1(r.flag_pgd20)}"] +
                ([f"{f1(r.flag_adaptive)} ({f1(r.adaptive_nc, 2)})"] if has_ad else []) +
                [f"{f1(r.splice64_auc, 3)} / {f1(r.splice64_f1, 3)}", f1(r.splice32_detected), f1(r.embed_s, 2)] for r in a.itertuples()]
        cap = (f"Same blind fragile scheme with different embedding domains, step ∆ calibrated to the PSNR of ours, thresholds "
               f"re-fixed on the 80 development images for each variant ({int(a.n_images.iloc[0]):,} test images; %). "
               "Source: results_v2/embed_ablation/summary.csv.")
        md += [f"## Table 5\n\n{cap}\n\n", md_table(hdr, rows)]; tex.append(tex_table(cap, hdr, rows, "tab:ablation"))
    else:
        missing.append("Table 5 (run eval_embed_ablation.py)")

    # ---------------- Table 6 (key dependence)
    k = read("key_variation/summary.csv")
    if k is not None:
        ths = [c[3:] for c in k.columns if c.startswith("fa_") and c.count("_") == 1]
        hdr = ["Key", "Development threshold"] + [f"False alarms @ {t}" for t in ths] + [f"64 px detected @ {t}" for t in ths]
        rows = []
        for r in k.to_dict("records"):
            pooled = r["key"].startswith("all")
            fa = [(f"{f1(r['fa_' + t])} [{f1(r['fa_' + t + '_lo'])}, {f1(r['fa_' + t + '_hi'])}]; keys {f1(r['fa_' + t + '_keymin'])}–{f1(r['fa_' + t + '_keymax'])}"
                   if pooled else f1(r["fa_" + t])) for t in ths]
            rows.append([r["key"], f1(r.get("dev_threshold"), 2)] + fa + [f1(r["det64_" + t]) for t in ths])
        cap = (f"Dependence on the secret key: false alarms on untouched watermarked test images and detection of one 64 x 64 "
               f"copy-move edit per image, at several tamper thresholds (0.19 = published), for {len(k) - 1} independent keys (%). "
               "Pooled row: 95% Wilson interval and range over keys. Source: results_v2/key_variation/summary.csv.")
        md += [f"## Table 6\n\n{cap}\n\n", md_table(hdr, rows)]; tex.append(tex_table(cap, hdr, rows, "tab:keys"))
    else:
        missing.append("Table 6 (run eval_key_variation.py)")

    if missing:
        md.append("\n**Not yet available:** " + "; ".join(missing) + "\n")
    open(os.path.join(OUT, "new_tables.md"), "w", encoding="utf-8").write("".join(md))
    open(os.path.join(OUT, "new_tables.tex"), "w", encoding="utf-8").write("".join(tex))
    print("".join(md))


if __name__ == "__main__":
    main()
