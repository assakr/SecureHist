def embed_block(cb_block, wm_vector, gain):
    coeffs = pywt.dwt2(cb_block, 'haar')
    LL, (HL, LH, HH) = coeffs
    
    U_HL, S_HL, V_HL = np.linalg.svd(HL, full_matrices=False)
    U_LH, S_LH, V_LH = np.linalg.svd(LH, full_matrices=False)
    
    S_HL_new = S_HL * (1.0 + gain * wm_vector[0:8])
    S_LH_new = S_LH * (1.0 + gain * wm_vector[8:16])
    
    HL_new = np.dot(U_HL, np.dot(np.diag(S_HL_new), V_HL))
    LH_new = np.dot(U_LH, np.dot(np.diag(S_LH_new), V_LH))
    
    cb_new = pywt.idwt2((LL, (HL_new, LH_new, HH)), 'haar')
    return cb_new.astype(np.float32)


def embed_adaptive_dwt_svd_cb(img_rgb, patient_id):
    img_rgb = ensure_even_crop(img_rgb, BLOCK_SIZE)

