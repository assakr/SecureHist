def ensure_even_crop(img, block_size=BLOCK_SIZE):
    h, w = img.shape[:2]
    h2 = (h // block_size) * block_size
    w2 = (w // block_size) * block_size
    return img[:h2, :w2].copy()

def normalize_01(arr):
    arr = arr.astype(np.float32)
    mn, mx = float(arr.min()), float(arr.max())
    if mx - mn < EPS:
        return np.zeros_like(arr, dtype=np.float32)
    return (arr - mn) / (mx - mn)

def zscore(v):
    v = v.astype(np.float32)
    return (v - np.mean(v)) / (np.std(v) + EPS)

def local_variance(channel, ksize=7):
    channel = channel.astype(np.float32)
    mean = cv2.blur(channel, (ksize, ksize))
    mean_sq = cv2.blur(channel * channel, (ksize, ksize))
    var = np.maximum(mean_sq - mean * mean, 0.0)
    var = cv2.GaussianBlur(var, (0, 0), 1.0)
    return var



