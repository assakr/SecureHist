def get_roi_mask(img_rgb):
    ycrcb = cv2.cvtColor(img_rgb, cv2.COLOR_RGB2YCrCb)
    y = ycrcb[:, :, 0]

    _, tissue = cv2.threshold(y, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)

    kernel = np.ones((5, 5), np.uint8)
    tissue = cv2.morphologyEx(tissue, cv2.MORPH_OPEN, kernel)
    tissue = cv2.morphologyEx(tissue, cv2.MORPH_CLOSE, kernel)
    tissue = cv2.medianBlur(tissue, 5)

    return (tissue > 0).astype(np.uint8)

def block_selection_maps(img_rgb):
    img_rgb = ensure_even_crop(img_rgb, BLOCK_SIZE)
    ycrcb = cv2.cvtColor(img_rgb, cv2.COLOR_RGB2YCrCb).astype(np.float32)
    cb = ycrcb[:, :, 2]

    roi_mask = get_roi_mask(img_rgb)
    texture_norm = normalize_01(local_variance(cb, ksize=7))

    h, w = cb.shape
    bh, bw = h // BLOCK_SIZE, w // BLOCK_SIZE
    selected = np.zeros((bh, bw), dtype=bool)

    roi_means, tex_means = [], []

    for r in range(0, h, BLOCK_SIZE):
        for c in range(0, w, BLOCK_SIZE):
            roi_block = roi_mask[r:r+BLOCK_SIZE, c:c+BLOCK_SIZE]
            tex_block = texture_norm[r:r+BLOCK_SIZE, c:c+BLOCK_SIZE]
            roi_means.append(float(np.mean(roi_block)))
            tex_means.append(float(np.mean(tex_block)))

    tex_arr = np.array(tex_means, dtype=np.float32)
    adaptive_tex_thr = max(TEXTURE_FLOOR, float(np.percentile(tex_arr, 40)))

    idx = 0
    for i, r in enumerate(range(0, h, BLOCK_SIZE)):
        for j, c in enumerate(range(0, w, BLOCK_SIZE)):
            roi_mean = roi_means[idx]
            tex_mean = tex_means[idx]
            is_tissue = roi_mean >= 0.10
            is_textured = tex_mean >= adaptive_tex_thr
            selected[i, j] = is_tissue and is_textured
            idx += 1

    if int(selected.sum()) < MIN_SELECTED_BLOCKS:
        candidates = []
        idx = 0
        for i, r in enumerate(range(0, h, BLOCK_SIZE)):
            for j, c in enumerate(range(0, w, BLOCK_SIZE)):
                roi_mean = roi_means[idx]
                tex_mean = tex_means[idx]
                if roi_mean >= 0.05:
                    candidates.append((tex_mean, i, j))
                idx += 1

        candidates.sort(reverse=True)
        selected[:, :] = False
        for _, i, j in candidates[:min(MIN_SELECTED_BLOCKS, len(candidates))]:
            selected[i, j] = True

    return roi_mask, texture_norm, selected

