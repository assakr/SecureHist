def init_cnn_block(force_reload=False):
    """
    Initialize a real CNN backbone for image-feature extraction.
    Preferred path: pretrained ResNet18 from torchvision.
    Fallback: randomly initialized ResNet18 if pretrained weights are unavailable.
    """
    global _CNN_MODEL, _CNN_PREPROCESS, _CNN_MODEL_STATUS

    if not USE_CNN_BLOCK:
        _CNN_MODEL_STATUS = "disabled"
        return None

    if _CNN_MODEL is not None and not force_reload:
        return _CNN_MODEL

    if torch is None or models is None or transforms is None:
        _CNN_MODEL_STATUS = "torchvision_unavailable"
        return None

    try:
        weights = models.ResNet18_Weights.DEFAULT
        model = models.resnet18(weights=weights)
        _CNN_MODEL_STATUS = "pretrained"
        mean = weights.transforms().mean
        std = weights.transforms().std
    except Exception:
        model = models.resnet18(weights=None)
        _CNN_MODEL_STATUS = "random_init"
        mean = [0.485, 0.456, 0.406]
        std = [0.229, 0.224, 0.225]

    model.fc = torch.nn.Identity()
    model.eval()
    model = model.to(DEVICE)

    _CNN_PREPROCESS = transforms.Compose([
        transforms.ToPILImage(),
        transforms.Resize((CNN_INPUT_SIZE, CNN_INPUT_SIZE)),
        transforms.ToTensor(),
        transforms.Normalize(mean=mean, std=std),
    ])
    _CNN_MODEL = model
    return _CNN_MODEL

def cnn_extract_features(img_rgb):
    """
    Extract a CNN feature vector from an RGB image using the initialized backbone.
    Returns a normalized 1D numpy vector and a status string.
    """
    model = init_cnn_block()
    if model is None or _CNN_PREPROCESS is None or torch is None:
        return None, _CNN_MODEL_STATUS

    img_rgb = np.asarray(img_rgb, dtype=np.uint8)
    tensor = _CNN_PREPROCESS(img_rgb).unsqueeze(0).to(DEVICE)

    with torch.no_grad():
        feats = model(tensor).squeeze(0).detach().cpu().float()

    norm = torch.norm(feats) + 1e-8
    feats = feats / norm
    return feats.numpy().astype(np.float32), _CNN_MODEL_STATUS

def cnn_shift_score(reference_img_rgb, suspect_img_rgb):
    """
    CNN-based drift score in [0,1], where larger values indicate larger change.
    Uses cosine similarity between CNN embeddings.
    """
    ref_feat, status = cnn_extract_features(reference_img_rgb)
    sus_feat, _ = cnn_extract_features(suspect_img_rgb)

    if ref_feat is None or sus_feat is None:
        return 0.0, 1.0, status

    cos_sim = float(np.dot(ref_feat, sus_feat) / ((np.linalg.norm(ref_feat) * np.linalg.norm(sus_feat)) + 1e-8))
    cos_sim = float(np.clip(cos_sim, -1.0, 1.0))
    shift = 0.5 * (1.0 - cos_sim)  # maps [-1,1] similarity into [0,1] shift
    shift = float(np.clip(shift, 0.0, 1.0))
    return shift, cos_sim, status

