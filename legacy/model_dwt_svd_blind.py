def get_auc_and_scores(ref_img_rgb, tampered_img_rgb, pid, selected_blocks, gt_blocks):
    """Blind tamper score per selected block = mean QIM distance in the TAMPERED image.
    ref_img_rgb is ignored (kept for API compatibility)."""
    dist_map, _ = compute_block_qim_distance_map(tampered_img_rgb, pid, selected_blocks)
    if SCORE_SMOOTHING > 1:
        from scipy.ndimage import uniform_filter
        valid = np.isfinite(dist_map).astype(np.float32)
        filled = np.where(np.isfinite(dist_map), dist_map, 0.0)
        dist_map = uniform_filter(filled, SCORE_SMOOTHING, mode="nearest") / np.maximum(
            uniform_filter(valid, SCORE_SMOOTHING, mode="nearest"), 1e-6)

    coords = [
        (i, j)
        for i in range(selected_blocks.shape[0])
        for j in range(selected_blocks.shape[1])
        if selected_blocks[i, j]
    ]
    score = np.array([0.0 if np.isnan(dist_map[i, j]) else dist_map[i, j] for i, j in coords],
                     dtype=np.float32)
    global _LAST_GRID
    _LAST_GRID = (selected_blocks.shape, coords)

    auc_val = float("nan")
    if len(np.unique(gt_blocks)) >= 2:
        auc_val = float(roc_auc_score(gt_blocks, score))
    return auc_val, score, coords


def get_classification_metrics(gt_blocks, score_blocks):
    thr = float(TAMPER_THRESHOLD)
    pred = (score_blocks >= thr).astype(np.uint8)
    if MASK_OPENING and _LAST_GRID is not None and len(_LAST_GRID[1]) == len(pred):
        from scipy.ndimage import binary_opening
        shape, coords = _LAST_GRID
        grid = np.zeros(shape, dtype=bool)
        for (i, j), v in zip(coords, pred):
            grid[i, j] = bool(v)
        grid = binary_opening(grid, structure=np.ones((2, 2), dtype=bool))
        pred = np.array([grid[i, j] for i, j in coords], dtype=np.uint8)

    acc = accuracy_score(gt_blocks, pred)
    prec = precision_score(gt_blocks, pred, zero_division=0)
    rec = recall_score(gt_blocks, pred, zero_division=0)
    f1 = f1_score(gt_blocks, pred, zero_division=0)
    cm = confusion_matrix(gt_blocks, pred, labels=[0, 1])

    return acc, prec, rec, f1, cm, pred, thr


