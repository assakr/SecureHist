def qim_keybits(patient_id, block_row, block_col, n):
    seed_str = f"{patient_id}_{block_row}_{block_col}"
    seed = int(hashlib.sha256(seed_str.encode("utf-8")).hexdigest()[:8], 16)
    rng = np.random.default_rng(seed)
    return rng.integers(0, 2, n), rng.uniform(0.0, 1.0, n)   # key bits, key dither


def qim_quantize(s, bit, dither, step=QIM_STEP):
    offset = (dither + 0.5 * bit) * step
    return np.round((s - offset) / step) * step + offset


def qim_distance(s, bit, dither, step=QIM_STEP):
    """Normalised distance to the lattice of the expected bit: 0 = intact, 0.5 = opposite bit."""
    offset = (dither + 0.5 * bit) * step
    r = (s - offset) / step
    return np.abs(r - np.round(r))


def embed_block(cb_block, patient_id, block_row, block_col):
    LL, (HL, LH, HH) = pywt.dwt2(cb_block.astype(np.float64), 'haar')
    bits, dither = qim_keybits(patient_id, block_row, block_col, 2 * QIM_K)
    new_bands = []
    for band_idx, band in enumerate((HL, LH)):
        U, S, Vt = np.linalg.svd(band, full_matrices=False)
        for k in range(QIM_K):
            idx = band_idx * QIM_K + k
            S[k] = qim_quantize(S[k], bits[idx], dither[idx])
        new_bands.append(U @ np.diag(S) @ Vt)
    cb_new = pywt.idwt2((LL, (new_bands[0], new_bands[1], HH)), 'haar')
    return cb_new.astype(np.float32)


