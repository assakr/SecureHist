def attack_crop_restore(img_rgb, crop_ratio=0.12):
    h, w = img_rgb.shape[:2]
    ch, cw = int(h * crop_ratio), int(w * crop_ratio)
    cropped = img_rgb[ch:h-ch, cw:w-cw]
