    k = min(top_k, len(coords))

    if mode == "random":
        rng = np.random.default_rng(seed)
        pick_idx = rng.choice(len(coords), size=k, replace=False)
        return [coords[idx] for idx in pick_idx]

    corr_map = compute_block_correlation_map(ref_img_rgb, pid, selected_blocks)

    scored = []
    for i, j in coords:
        val = corr_map[i, j]
        if np.isnan(val):
            val = 0.0
        scored.append((abs(val), (i, j)))

    scored.sort(reverse=True, key=lambda x: x[0])
    return [coord for _, coord in scored[:k]]


