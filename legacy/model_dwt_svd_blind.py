    for i, j in coords:
        r = i * BLOCK_SIZE
        c = j * BLOCK_SIZE

        br1, bc1 = r, c
        br2, bc2 = r + BLOCK_SIZE, c + BLOCK_SIZE

        tr1, tc1 = r0, c0
        tr2, tc2 = r0 + patch, c0 + patch

        overlap = not (br2 <= tr1 or br1 >= tr2 or bc2 <= tc1 or bc1 >= tc2)
        gt_blocks.append(1 if overlap else 0)

    return np.array(gt_blocks, dtype=np.uint8), coords


