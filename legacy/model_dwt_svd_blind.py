def compute_block_qim_distance_map(img_rgb, patient_id, selected_blocks):
    """Per-block mean QIM distance (0 = watermark intact, ~0.25 = no watermark / tampered)."""
    img_rgb = ensure_even_crop(img_rgb, BLOCK_SIZE)
    cb = cv2.cvtColor(img_rgb, cv2.COLOR_RGB2YCrCb).astype(np.float64)[:, :, 2]
    h, w = cb.shape
    dist_map = np.full((h // BLOCK_SIZE, w // BLOCK_SIZE), np.nan, dtype=np.float32)
    bit_ok_map = np.full_like(dist_map, np.nan)
    for i, r in enumerate(range(0, h, BLOCK_SIZE)):
        for j, c in enumerate(range(0, w, BLOCK_SIZE)):
            if not selected_blocks[i, j]:
                continue
            LL, (HL, LH, HH) = pywt.dwt2(cb[r:r+BLOCK_SIZE, c:c+BLOCK_SIZE], 'haar')
            bits, dither = qim_keybits(patient_id, i, j, 2 * QIM_K)
            d = []
            for band_idx, band in enumerate((HL, LH)):
                S = np.linalg.svd(band, compute_uv=False)
                for k in range(QIM_K):
                    idx = band_idx * QIM_K + k
                    d.append(qim_distance(S[k], bits[idx], dither[idx]))
            d = np.asarray(d)
            dist_map[i, j] = float(d.mean())
            bit_ok_map[i, j] = float((d < 0.25).mean())
    return dist_map, bit_ok_map


def compute_block_correlation_map(img_rgb, patient_id, selected_blocks):
    """Blind per-block integrity in [0, 1]: 1 - 4 * mean QIM distance (1 = intact, ~0 = random)."""
    dist_map, _ = compute_block_qim_distance_map(img_rgb, patient_id, selected_blocks)
    return (1.0 - 4.0 * dist_map).astype(np.float32)


def extract_ncc_reference(reference_img_rgb, suspect_img_rgb, patient_id, selected_blocks):
    """BLIND watermark NC from the suspect image only (reference argument kept for API
    compatibility and ignored): NC = 1 - 2*BER over all key bits. 1 = intact, ~0 = absent."""
    _, bit_ok_map = compute_block_qim_distance_map(suspect_img_rgb, patient_id, selected_blocks)
    vals = bit_ok_map[np.isfinite(bit_ok_map)]
    if vals.size == 0:
        return 0.0
    return float(2.0 * np.mean(vals) - 1.0)

