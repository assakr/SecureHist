def get_prediction(img_rgb, classifier=None):
    """
    Safe prediction wrapper.

    Priority:
    1) If a user-defined callable classifier is supplied, use it.
    2) Else if a global `diagnostic_model_predict` exists, use it.
    3) Else return a heuristic fallback prediction.

    Returns:
        pred_label (int), confidence (float in [0,1])

    NOTE:
    The fallback branch is only for pipeline continuity and demonstration.
    It must NOT be presented as a real clinical diagnosis.
    """
    if classifier is not None and callable(classifier):
        pred, conf = classifier(img_rgb)
        return int(pred), float(np.clip(conf, 0.0, 1.0))

    if "diagnostic_model_predict" in globals() and callable(globals()["diagnostic_model_predict"]):
        pred, conf = globals()["diagnostic_model_predict"](img_rgb)
        return int(pred), float(np.clip(conf, 0.0, 1.0))

    feats = simple_image_features(img_rgb)

    # Heuristic score only to quantify visual/structural change.
    score = (
        1.40 * feats["texture_energy"]
        + 0.90 * feats["tissue_ratio"]
        + 0.70 * feats["std_intensity"]
        + 0.50 * feats["cb_std"]
        - 0.60 * feats["mean_intensity"]
    )

    conf = 1.0 / (1.0 + np.exp(-3.0 * (score - 0.65)))
    pred = int(conf >= 0.50)
    return pred, float(conf)


