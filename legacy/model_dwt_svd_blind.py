def compute_roi_impact(gt_mask, roi_mask):
    gt_mask = gt_mask.astype(np.uint8)
    roi_mask = roi_mask.astype(np.uint8)

    tampered_pixels = np.sum(gt_mask == 1)
    if tampered_pixels == 0:
        return 0.0

    tampered_in_roi = np.sum((gt_mask == 1) & (roi_mask == 1))
    return float(tampered_in_roi / (tampered_pixels + 1e-8))


def compute_roi_detection_rate(gt_mask, score_map, threshold=None):
    if threshold is None:
        threshold = TAMPER_THRESHOLD

    pred_map = (score_map >= threshold).astype(np.uint8)

    roi_pixels = np.sum(gt_mask == 1)
    if roi_pixels == 0:
        return 0.0

    detected_roi = np.sum((gt_mask == 1) & (pred_map == 1))
    return float(detected_roi / (roi_pixels + 1e-8))


