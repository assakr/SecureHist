def cnn_extract_layer4_features(img_rgb):
    model = init_cnn_block()
    if model is None or _CNN_PREPROCESS is None or torch is None:
        return None
    img_rgb = np.asarray(img_rgb, dtype=np.uint8)
    tensor = _CNN_PREPROCESS(img_rgb).unsqueeze(0).to(DEVICE)
    with torch.no_grad():
        x = model.conv1(tensor)
        x = model.bn1(x)
        x = model.relu(x)
        x = model.maxpool(x)
        x = model.layer1(x)
        x = model.layer2(x)
        x = model.layer3(x)
        feats2d = model.layer4(x).squeeze(0).detach().cpu().float()
    return feats2d.numpy().astype(np.float32)

def generate_semantic_drift_heatmap(ref_feat2d, sus_feat2d, original_img_shape):
    if ref_feat2d is None or sus_feat2d is None:
        return np.zeros((original_img_shape[0], original_img_shape[1], 3), dtype=np.uint8)
    ref_norm = np.linalg.norm(ref_feat2d, axis=0, keepdims=True) + 1e-8
    sus_norm = np.linalg.norm(sus_feat2d, axis=0, keepdims=True) + 1e-8
    ref_normed = ref_feat2d / ref_norm
    sus_normed = sus_feat2d / sus_norm
    cos_sim = np.sum(ref_normed * sus_normed, axis=0)
    drift = 0.5 * (1.0 - cos_sim)
    return generate_forensic_heatmap(drift, original_img_shape, cv2.COLORMAP_HOT)

def run_forensic_agent(model, processor, h_e_image_pil, ncc_heatmap_pil, drift_heatmap_pil, cnn_prediction, risk_score, ncc_mean):
    if model is None or processor is None:
        return "VLM Model not loaded. Check GPU/Dependencies."
    system_prompt = "You are an expert Forensic Pathology AI Agent. Analyze multimodal evidence to detect image tampering or adversarial attacks.\nYou will receive 3 images:\n1. H&E Tissue Image.\n2. Integrity Heatmap (Red = Watermark damaged/low NCC; Blue = Intact).\n3. Semantic Drift Map (Red = High deep-feature drift; Blue = Stable)."
    user_prompt = f"Analyze the images step-by-step:\nStep 1 (Perception): Describe the tissue in Image 1. Any visible unnatural patches?\nStep 2 (Integrity): Examine Image 2. Is the red damage localized to the background (RONI) or tissue (ROI)?\nStep 3 (Semantic Drift): Examine Image 3. Is there massive red drift in tissue areas even if Image 1 looks normal?\nStep 4 (Synthesis): The fast CNN classified this as '{cnn_prediction}', Risk Score is {risk_score:.4f}, and Mean NCC is {ncc_mean:.4f}.\nCRITICAL RULE: If Image 1 looks clean, but Image 2 shows micro-anomalies AND Image 3 shows massive drift, you MUST explicitly classify this as a STEALTHY ADVERSARIAL ATTACK (FGSM)."
    messages = [
        {"role": "system", "content": system_prompt},
        {
            "role": "user",
            "content": [
                {"type": "image", "image": h_e_image_pil},
                {"type": "image", "image": ncc_heatmap_pil},
                {"type": "image", "image": drift_heatmap_pil},
                {"type": "text", "text": user_prompt},
            ],
        }
    ]
    try:
        text = processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        inputs = processor(text=[text], images=[h_e_image_pil, ncc_heatmap_pil, drift_heatmap_pil], padding=True, return_tensors="pt").to(DEVICE)
        output_ids = model.generate(**inputs, max_new_tokens=512, temperature=0.1, top_p=0.9)
        generated_ids = [out_ids[len(in_ids):] for in_ids, out_ids in zip(inputs.input_ids, output_ids)]
        response = processor.batch_decode(generated_ids, skip_special_tokens=True)[0]
        if "STEALTHY ADVERSARIAL ATTACK" in response or "FGSM" in response:
            if float(risk_score) < 10 and float(ncc_mean) >= 0.99:
                response += "\n\n[GUARDRAIL OVERRIDE]: Agent anomaly detected. Defaulting to low-risk status as Risk Score and NCC are optimal."
        return response
    except Exception as e:
        return f"VLM Inference Error: {str(e)}"

